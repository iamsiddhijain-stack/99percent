#!/usr/bin/env python3
"""Builds content/book-images.js: which supplied book illustration belongs to which story.
Inputs: content/book-image-map.json   [[source PDF page, image no.], ...]  (team catalogue of images extracted from the book PDF)
        content/book-image-owners.json  per image: its vertical position on the book page and the story whose heading
                                        most recently precedes it (computed from the book PDF text and image positions)
An image belongs to the story it sits under, not merely a story whose page range includes the page.
Hand-checked: shared pages (OVERRIDE), chapter-opener images (CHAPTER_HERO).
An image on a page with almost no text, directly before a story's first page, opens that story (checked against the book).
Stories with no image of their own get a nearby illustration, flagged 'generic' so the page says so.
Images are the book's artwork, supplied by the team for a student prototype: not for public release without permission."""
import json, pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
rd = lambda n: json.loads((root/'content'/n).read_text())
disc, imap, own = rd('discoveries.json'), rd('book-image-map.json'), rd('book-image-owners.json')
S = {int(d['id'][5:]): {'a': d['bookReference']['pdfPages'][0], 'b': d['bookReference']['pdfPages'][-1], 'ch': int(d['chapterNumber']), 'sub': d['subcategory']} for d in disc}
OVERRIDE = {18: 8, 70: 48, 74: 52, 120: 111}
CHAPTER_HERO = {1: 7, 2: 33, 3: 57, 4: 79, 5: 99, 6: 119}
FRONT = {1, 2, 5, 6, 9, 12}
FRAGMENTS = {8, 32, 56, 78, 118}   # cropped background textures from chapter-opener pages: never used as a story picture
meta, stories = {}, {}
for p, k in imap:
    im = Image.open(root/f'img/book/b{k:03d}.jpg'); o = own[str(k)]
    meta[k] = [im.width, im.height, p, o['top']]
    if p in FRONT or k in FRAGMENTS: continue
    in_range = any(s['a'] <= p <= s['b'] for s in S.values())
    n = OVERRIDE.get(k) or (o['owner'] if in_range else None)
    if n: stories.setdefault(n, []).append(k)
for n in stories:
    stories[n].sort(key=lambda k: (meta[k][2], meta[k][3]))
    big = [k for k in stories[n] if min(meta[k][0], meta[k][1]) >= 420]      # sizes are after enlargement: >=420 means >=~140px original
    if big: stories[n].remove(big[0]); stories[n].insert(0, big[0])
# generic: a nearby illustration for stories without one (never a chapter-opener image, never the same image twice if avoidable)
heroes = {v[0] for v in stories.values()} | set(CHAPTER_HERO.values())
owner_ch = {k: S[m]['ch'] for m, v in stories.items() for k in v}
spare = [k for p, k in imap if p not in FRONT and k not in FRAGMENTS and k not in heroes and min(meta[k][0], meta[k][1]) >= 300]
generic, used = {}, {}
for n in sorted(S, key=lambda n: S[n]['a']):
    if n in stories: continue
    cands = sorted(spare, key=lambda k: (used.get(k, 0), owner_ch.get(k, S[n]['ch']) != S[n]['ch'], abs(meta[k][2] - S[n]['a'])))
    k = cands[0]; used[k] = used.get(k, 0) + 1; generic[n] = k
js = 'window.BOOKIMG=' + json.dumps({'stories': stories, 'generic': generic, 'chapters': CHAPTER_HERO, 'meta': meta}, separators=(',', ':')) + ';'
(root/'content/book-images.js').write_text('/* GENERATED by tools/build_book_images.py */\n' + js)
print(len(stories), 'stories with own images;', len(generic), 'with a nearby illustration')
