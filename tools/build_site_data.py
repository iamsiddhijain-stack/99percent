#!/usr/bin/env python3
"""Builds content/site-data.js (loaded by index.html) from the content database.
Run from the project root:  python3 tools/build_site_data.py
Inputs: content/discoveries.json, chapters.json, subcategories.json, map-pins.json
Book content is copied, never rewritten. window.SITE = {chapters, subs, stories}."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rd = lambda n: json.loads((root/'content'/n).read_text())
disc, chapters, subs, pins = rd('discoveries.json'), rd('chapters.json'), rd('subcategories.json'), rd('map-pins.json')
num = lambda i: int(i.split('-')[1])
stories = []
for d in disc:
    p = pins['pins'].get(d['id'], 'absent')
    nyc = p != 'absent'                      # the 21 New York City stories
    pin = None
    if p and p != 'absent':
        pin = {'ll': [p['lat'], p['lng']], 'basis': p['basis'], 'offset': bool(p.get('displayOffset')),
               'src': p.get('coordSource', pins['defaultCoordSource']), 'st': p.get('coordStatus', 'estimated'), 'rad': p.get('radiusMetres', 150)}
    b, o, g = d['bookContent'], d['observation'], d['geography']
    flags = list(b.get('verificationFlag') or [])
    if g.get('note') and g['note'] not in flags: flags.append(g['note'])
    stories.append({
        'n': num(d['id']), 'id': d['id'], 'title': d['title'], 'orig': d['originalTitle'], 'kicker': d['kicker'],
        'chapter': d['chapter'], 'cn': d['chapterNumber'], 'sub': d['subcategory'], 'pages': d['bookReference']['pdfPages'],
        'summary': b['summary'], 'fn': b['function'], 'hist': b['historicalContext'], 'take': b['keyTakeaway'],
        'look': o['whatToLookFor'], 'clues': o['visualClues'],
        'places': [{'city': x['city'], 'country': x.get('country'), 'hood': x['neighbourhood'], 'spec': x['specific'], 'prec': x['precision']} for x in g['places']],
        'flags': flags,
        'layerB': [{'claim': a.get('claim'), 'hood': a.get('neighbourhood'), 'accessed': a.get('accessed'), 'verification': a.get('verification'),
                    'sources': a.get('sources', []), 'addresses': a.get('addresses', [])} for a in d.get('additionalResearch', [])],
        'cited': d.get('bookCitedSources', []), 'rel': [num(r) for r in d.get('relatedDiscoveries', [])],
        'kw': d.get('autoKeywords', []), 'nyc': nyc, 'pin': pin})
out = {
    'chapters': [{'n': c['number'], 'title': c['displayTitle'], 'intro': c['editorialIntro'], 'page': c['pdfTitlePage'], 'subs': c['subcategories']} for c in chapters],
    'subs': [{'name': s['name'], 'chapter': s['chapter'], 'cn': s['chapterNumber'], 'intro': s['introSummary'], 'page': s['introPdfPage'], 'ids': [num(i) for i in s['storyIds']]} for s in subs],
    'stories': stories}
js = ('/* GENERATED by tools/build_site_data.py from content/*.json. Do not edit by hand. */\n'
      'window.SITE=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
(root/'content/site-data.js').write_text(js)
print(len(stories), 'stories;', sum(s['nyc'] for s in stories), 'NYC;', sum(1 for s in stories if s['pin']), 'pinned;',
      sum(1 for s in stories if s['layerB']), 'with Layer B;', len(js)//1024, 'KB')
